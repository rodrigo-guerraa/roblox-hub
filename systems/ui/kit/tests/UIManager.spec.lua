return function()
	local ReplicatedStorage = game:GetService("ReplicatedStorage")
	local UIManager = require(ReplicatedStorage:WaitForChild("UIManager"))

	local function panel()
		local frame = Instance.new("Frame")
		frame.Visible = false
		return frame
	end

	afterEach(function()
		UIManager.setTutorialLock(false)
	end)

	describe("open / close / toggle", function()
		it("shows and hides a registered panel", function()
			local frame = panel()
			UIManager.register("SpecOpen", frame)
			UIManager.open("SpecOpen")
			expect(frame.Visible).to.equal(true)
			UIManager.close("SpecOpen")
			expect(frame.Visible).to.equal(false)
			UIManager.toggle("SpecOpen")
			expect(frame.Visible).to.equal(true)
			UIManager.close("SpecOpen")
		end)

		it("ignores unknown panel names", function()
			expect(function()
				UIManager.open("SpecMissing")
				UIManager.close("SpecMissing")
				UIManager.toggle("SpecMissing")
			end).never.to.throw()
		end)

		it("closes the other panel when one opens", function()
			local a, b = panel(), panel()
			UIManager.register("SpecA", a)
			UIManager.register("SpecB", b)
			UIManager.open("SpecA")
			task.wait()
			UIManager.open("SpecB")
			task.wait()
			expect(a.Visible).to.equal(false)
			expect(b.Visible).to.equal(true)
			UIManager.close("SpecB")
		end)
	end)

	describe("tutorial lock", function()
		it("blocks panels outside the allow list", function()
			local frame = panel()
			UIManager.register("SpecLocked", frame)
			UIManager.setTutorialLock(true, { "SpecAllowed" })
			expect(UIManager.canOpen("SpecLocked")).to.equal(false)
			expect(UIManager.canOpen("SpecAllowed")).to.equal(true)
			UIManager.open("SpecLocked")
			expect(frame.Visible).to.equal(false)
		end)

		it("allows everything once unlocked", function()
			UIManager.setTutorialLock(false)
			expect(UIManager.canOpen("Anything")).to.equal(true)
		end)
	end)

	describe("tutorial targets", function()
		it("stores and returns a target", function()
			local frame = panel()
			UIManager.registerTutorialTarget("SpecTarget", frame)
			expect(UIManager.getTutorialTarget("SpecTarget")).to.equal(frame)
		end)
	end)
end
